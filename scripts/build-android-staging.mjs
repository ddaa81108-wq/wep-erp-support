import { build } from 'esbuild';
import console from 'node:console';
import { readFileSync, cpSync, mkdirSync, writeFileSync } from 'node:fs';
import { join, resolve, sep } from 'node:path';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
const current=JSON.parse(readFileSync('var/android-staging/current.json','utf8'));
const run=resolve(current.run);
if(!run.startsWith(resolve('var/android-staging')+sep))throw new Error('Not a staging run');
const manifest=JSON.parse(readFileSync(join(run,'manifest.json'),'utf8'));
if(manifest.synthetic!==true)throw new Error('Not synthetic');
execFileSync('git',['diff','--quiet','HEAD','--','src']);
const commit=execFileSync('git',['rev-parse','HEAD'],{encoding:'utf8'}).trim();
if(commit!==manifest.sourceCommit)throw new Error('Source changed since seeding');
const runtime=join(run,'runtime');mkdirSync(runtime,{recursive:true});
const metadata={version:JSON.parse(readFileSync('package.json','utf8')).version,commit,builtAt:new Date().toISOString(),dirty:true};
await build({entryPoints:['scripts/android-staging.ts'],bundle:true,platform:'node',format:'esm',target:'node24',outfile:join(runtime,'server/main.mjs'),define:{__BUILD_INFO__:JSON.stringify(metadata)},banner:{js:"import { createRequire as __createRequire } from 'node:module'; const require = __createRequire(import.meta.url);"}});
cpSync('dist/web',join(runtime,'web'),{recursive:true});
writeFileSync(join(runtime,'build-proof.json'),JSON.stringify({...metadata,sourceCommit:commit,synthetic:true,note:'dirty=true: staging launcher is uncommitted integration tooling; financial src matches commit. Frozen bundled runtime, independent of later workspace updates.',serverSha256:createHash('sha256').update(readFileSync(join(runtime,'server/main.mjs'))).digest('hex')},null,2));
console.log('Frozen staging runtime built: '+runtime);

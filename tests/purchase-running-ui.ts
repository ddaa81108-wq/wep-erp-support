import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
import { chromium, expect } from '@playwright/test';
import { createApp, listen } from '../src/server/app.ts';
import { loadConfig } from '../src/server/config.ts';
import { openDatabase } from '../src/server/db/database.ts';
import { fixtureAdmin } from './helpers/financialFixture.ts';
import { createSession } from '../src/server/security/sessions.ts';
import { listPurchases } from '../src/server/domain/purchaseQueries.ts';
import { createPurchaseEntry } from '../src/server/domain/purchaseEntryCommands.ts';
import { finalizePurchaseDay, setPurchaseOpening } from '../src/server/domain/purchaseDayCommands.ts';

const db=openDatabase(':memory:');
const actor=fixtureAdmin(db);
let state=listPurchases(db,actor,'al_bayan',null,null);
setPurchaseOpening(db,actor,'al_bayan',{expectedDayVersion:state.day.version,previousDebtUnits:1000,previousVodafoneUnits:0},'test');
state=listPurchases(db,actor,'al_bayan',null,null);
createPurchaseEntry(db,actor,'al_bayan',{requestId:'running-ui-opening',expectedDayVersion:state.day.version,itemCode:'custom',itemLabel:'رصيد اليوم السابق للاختبار',egpValueUnits:0,calculationMode:'divide',exchangeRate:'1',paidUnits:0,vodafoneConsumedUnits:1},'test');
state=listPurchases(db,actor,'al_bayan',null,null);
finalizePurchaseDay(db,actor,'al_bayan',{requestId:'running-ui-finalize',expectedDayVersion:state.day.version},'test');
const server=createApp(db,loadConfig({databasePath:':memory:',publicOrigin:'',secureCookie:false,internetRequired:false,pushPublicKey:'',pushPrivateKey:''}));
const browser=await chromium.launch();
try {
  await listen(server,'127.0.0.1',0);
  const address=server.address();assert.ok(address&&typeof address!=='string');
  const base=`http://127.0.0.1:${address.port}`;
  const context=await browser.newContext({viewport:{width:1440,height:1000}});
  const session=createSession(db,actor.id,'1',12);
  await context.addCookies([{name:'abdo_session',value:session.token,url:base}]);
  const page=await context.newPage();
  const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
  page.on('dialog',dialog=>void dialog.accept());
  await page.goto(base+'/erp');
  await page.getByRole('button',{name:'قسم المشتريات',exact:true}).click();
  const opening=page.locator('.purchase-day-opening .purchase-carry-value');
  await expect(opening.last()).toHaveText('1,000');
  await expect(page.locator('.purchase-inline-editor .purchase-running-balance')).toHaveText('1,000');
  const editor=page.locator('.purchase-inline-editor');
  await editor.getByLabel('القيمة ج.م',{exact:true}).fill('300');
  await editor.getByLabel('سعر الصرف',{exact:true}).fill('1');
  await expect(editor.locator('.purchase-running-balance')).toHaveText('1,300');
  await editor.getByRole('button',{name:'اعتماد الصف',exact:true}).click();
  await expect(page.locator('.purchase-row .purchase-running-balance').last()).toHaveText('1,300');
  await editor.getByLabel('المسدد',{exact:true}).fill('200');
  await expect(editor.locator('.purchase-running-balance')).toHaveText('1,100');
  await editor.getByRole('button',{name:'اعتماد الصف',exact:true}).click();
  await expect(page.locator('.purchase-row .purchase-running-balance').last()).toHaveText('1,100');
  await editor.getByLabel('القيمة ج.م',{exact:true}).fill('500');
  await editor.getByLabel('سعر الصرف',{exact:true}).fill('1');
  await editor.getByLabel('المسدد',{exact:true}).fill('100');
  await editor.getByRole('button',{name:'اعتماد الصف',exact:true}).click();
  await expect(page.locator('.purchase-row .purchase-running-balance')).toHaveText(['1,000','1,300','1,100','1,500']);
  await expect(page.locator('.purchase-metrics')).toContainText('1,500');
  await page.reload();
  await expect(page.locator('.purchase-row .purchase-running-balance').last()).toHaveText('1,500');
  mkdirSync('artifacts/purchase-running',{recursive:true});
  await page.screenshot({path:'artifacts/purchase-running/desktop.png',fullPage:true});
  // Finalizing an otherwise completed day must immediately expose the new carry row.
  await page.getByRole('button',{name:'ترحيل اليوم',exact:true}).click();
  await expect(opening.last()).toHaveText('1,500');
  await expect(page.locator('.purchase-day-closing-value').last()).toHaveText('1,500');
  await expect(editor.locator('.purchase-running-balance')).toHaveText('1,500');
  await page.screenshot({path:'artifacts/purchase-running/after-finalize.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'artifacts/purchase-running/mobile.png',fullPage:true});
  const align=await page.locator('.purchase-grid-head > span').nth(7).boundingBox();
  const carry=await opening.last().boundingBox();
  assert.ok(align&&carry);assert.ok(Math.abs(align.x-carry.x)<2,'Carry stays in the remaining column on mobile.');
  assert.deepEqual(errors,[]);
  console.log('PASS running purchase UI: carried1000, purchase1300, payment1100, combined1500, reload/finalize carry and mobile column alignment.');
  await context.close();
} finally {
  await browser.close();server.closeRealtimeConnections();server.closeAllConnections();
  await new Promise<void>(done=>server.close(()=>done()));db.close();
}

export function serverErrorText(code: string, original: string, locale = language) {
  if (locale === 'ar') return original;
  return (
    (Object.hasOwn(messages, code) ? messages[code] : undefined) ??
    (/\p{Script=Arabic}/u.test(original)
      ? `Unable to complete the request (${code}). Review your input or contact administration.`
      : original)
  );
}

export function systemText(original: string) {
  return uiText(original);
}
